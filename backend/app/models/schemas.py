from typing import Any
from pydantic import BaseModel, Field

# ============================================================
# SPEECH / AUDIO SCHEMAS
# ============================================================

class AudioUploadResponse(BaseModel):
    file_id: str
    filename: str
    file_size_bytes: int
    duration_seconds: float | None = None
    format: str
    message: str = "Audio uploaded successfully"

class TimestampSegmentSchema(BaseModel):
    text: str
    start: float
    end: float
    speaker: str | None = None

class TranscribeRequest(BaseModel):
    file_id: str
    return_timestamps: bool = True

class TranscribeResponse(BaseModel):
    file_id: str
    text: str
    segments: list[TimestampSegmentSchema] = Field(default_factory=list)
    language: str = "en"

# ============================================================
# CONVERSATION SCHEMAS
# ============================================================

class UtteranceSchema(BaseModel):
    speaker: str  # "Doctor" or "Patient"
    text: str
    start_time: float = 0.0
    end_time: float = 0.0

class ReconstructRequest(BaseModel):
    file_id: str | None = None
    text: str | None = None
    doctor_text: str | None = None
    patient_text: str | None = None
    doctor_segments: list[TimestampSegmentSchema] | None = None
    patient_segments: list[TimestampSegmentSchema] | None = None
    consultation_id: str | None = None

class ReconstructResponse(BaseModel):
    consultation_id: str | None = None
    utterances: list[UtteranceSchema]
    formatted_conversation: str
    total_utterances: int
    doctor_utterances_count: int
    patient_utterances_count: int

# ============================================================
# CLINICAL NOTE SCHEMAS
# ============================================================

class NoteMetadataSchema(BaseModel):
    generated_at: str
    model_name: str
    adapter_name: str
    is_draft: bool = True
    disclaimer: str = (
        "DRAFT — This clinical note was generated by an AI model "
        "and requires clinician verification before clinical use."
    )

class ClinicalNoteSchema(BaseModel):
    chief_complaint: str = "Not documented."
    history_of_present_illness: str = "Not documented."
    past_medical_history: str = "Not documented."
    medications: str = "Not documented."
    allergies: str = "Not documented."
    review_of_systems: str = "Not documented."
    examination: str = "Not documented."
    assessment: str = "Not documented."
    plan: str = "Not documented."
    raw_markdown: str | None = None
    metadata: NoteMetadataSchema

class GenerateNoteRequest(BaseModel):
    conversation: str
    consultation_id: str | None = None

class GenerateNoteResponse(BaseModel):
    clinical_note: ClinicalNoteSchema
    warnings: list[str] = Field(default_factory=list)

class UpdateNoteRequest(BaseModel):
    chief_complaint: str | None = None
    history_of_present_illness: str | None = None
    past_medical_history: str | None = None
    medications: str | None = None
    allergies: str | None = None
    review_of_systems: str | None = None
    examination: str | None = None
    assessment: str | None = None
    plan: str | None = None
    raw_markdown: str | None = None

class SavedNoteRecord(BaseModel):
    note_id: str
    filename: str
    created_at: str
    updated_at: str
    consultation_id: str | None = None
    clinical_note: ClinicalNoteSchema
    conversation: str | None = None

# ============================================================
# END-TO-END PIPELINE RESPONSE
# ============================================================

class EndToEndProcessResponse(BaseModel):
    file_id: str
    filename: str
    transcription: TranscribeResponse
    conversation: ReconstructResponse
    clinical_note: ClinicalNoteSchema
    note_id: str
    warnings: list[str] = Field(default_factory=list)
    processing_time_seconds: float

# ============================================================
# SYSTEM HEALTH SCHEMAS
# ============================================================

class HealthResponse(BaseModel):
    status: str
    version: str
    whisper_model_loaded: bool
    whisper_model_name: str
    clinical_llm_loaded: bool
    base_model_name: str
    lora_adapter_path: str
    device: str
