# MARKDOWN PARSER
# ============================================================

def parse_clinical_note_markdown(text: str) -> dict[str, str]:
    """
    Parse a generated Markdown clinical note into structured sections.
    Ensures raw dialogue text is never accepted as clinical documentation.
    """
    header_defs = [
        ("chief_complaint", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*Chief Complaint(?:\*\*|:)*\s*"),
        ("history_of_present_illness", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*History of Present Illness(?:\*\*|:)*\s*"),
        ("past_medical_history", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*(?:Relevant|Past) Medical History(?:\*\*|:)*\s*"),
        ("medications", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*(?:Current )?Medications(?:\*\*|:)*\s*"),
        ("allergies", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*Allergies(?:\*\*|:)*\s*"),
        ("review_of_systems", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*Review of Systems(?:\*\*|:)*\s*"),
        ("examination", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*(?:Physical )?Examination(?:\*\*|:)*\s*"),
        ("assessment", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*(?:Clinical )?Assessment(?:\*\*|:)*\s*"),
        ("plan", r"(?m)^\s*(?:#+\s*|[-*]\s*|\*\*\s*)*Plan(?: and Follow-up)?(?:\*\*|:)*\s*"),
    ]

    positions = []
    for key, pattern in header_defs:
        m = re.search(pattern, text, re.IGNORECASE)
        if m:
            positions.append((m.start(), m.end(), key))

    positions.sort(key=lambda x: x[0])

    sections: dict[str, str] = {}
    for i in range(len(positions)):
        start_content = positions[i][1]
        end_content = positions[i + 1][0] if i + 1 < len(positions) else len(text)
        key = positions[i][2]
        content = text[start_content:end_content].strip()
        # Clean any leading/trailing colon, asterisks, or whitespace
        content = re.sub(r"^[\s\:\*]+", "", content).strip()
        content = re.sub(r"[\*]+$", "", content).strip()

        # Reject/sanitize content if it contains raw dialogue speaker tags
        if re.search(r"(?i)\b(DOCTOR|PATIENT)\s*:", content):
            logger.warning(f"Raw dialogue found in section '{key}', sanitizing.")
            sanitized_lines = [
                line for line in content.splitlines()
                if not re.search(r"(?i)^\s*(?:DOCTOR|PATIENT)\s*:", line)
            ]
            content = "\n".join(sanitized_lines).strip()
            if not content:
                content = "Not documented."

        sections[key] = content if content else "Not documented."

    # Fallback for mock test inputs (only when no headers found and NO raw dialogue)
    if not sections and text.strip():
        # NEVER allow raw conversation dialogue to be assigned to clinical note sections
        if re.search(r"(?i)\b(DOCTOR|PATIENT)\s*:", text):
            logger.error("Raw dialogue detected with no clinical note headers! Rejecting.")
            for key, _ in header_defs:
                sections[key] = "Not documented."
        else:
            cleaned = text.strip()
            sections["chief_complaint"] = cleaned
            sections["history_of_present_illness"] = "Not documented."
            sections["past_medical_history"] = "Not documented."
            sections["medications"] = "Not documented."
            sections["allergies"] = "Not documented."
            sections["review_of_systems"] = "Not documented."
            sections["examination"] = "Not documented."
            sections["assessment"] = "Not documented."
            sections["plan"] = "Not documented."

    return sections


