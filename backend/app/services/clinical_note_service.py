class ClinicalNoteServiceError(Exception):
    """Raised when clinical note generation fails."""
    pass


class ClinicalNoteService:
    """
    Service for generating structured clinical consultation notes from conversations.
    Uses single-pass inference to prevent hallucination, cross-section repetition,
    and slow inference times.
    """

    def __init__(self, model_service: ModelService):
        self._model_service = model_service

    def _truncate_conversation(
        self,
        conversation: str,
        max_chars: int = 16000,
    ) -> str:
        """
        Truncate extremely long conversations while preserving the beginning
        and end. Default limit 16,000 chars (~4,000 tokens) preserves complete
        standard consultations without dropping medical history.
        """
        if len(conversation) <= max_chars:
            return conversation

        keep_start = int(max_chars * 0.4)
        keep_end = max_chars - keep_start

        truncated = (
            conversation[:keep_start]
            + "\n\n[... conversation truncated for length ...]\n\n"
            + conversation[-keep_end:]
        )

        logger.info(
            f"Conversation truncated: {len(conversation)} -> {len(truncated)} chars"
        )
        return truncated

    def generate_note(
        self,
        conversation: str,
    ) -> ClinicalNote:
        """
        Generate a complete clinical consultation note from a conversation in a single pass.

        Args:
            conversation: Doctor-patient conversation text formatted as
                "DOCTOR: ...\nPATIENT: ..."

        Returns:
            ClinicalNote with all 8 standard sections populated.

        Raises:
            ClinicalNoteServiceError: If generation fails.
        """
        if not self._model_service.is_loaded:
            raise ClinicalNoteServiceError(
                "Model not loaded. Cannot generate clinical note."
            )

        truncated_conv = self._truncate_conversation(conversation, max_chars=16000)

        user_message = (
            f"DOCTOR-PATIENT CONVERSATION:\n"
            f"{truncated_conv}\n\n"
            f"Generate the complete structured # CLINICAL CONSULTATION NOTE now:"
        )

        prompt = self._model_service.build_chat_prompt(
            system_message=CLINICAL_NOTE_SYSTEM_PROMPT,
            user_message=user_message,
        )

        logger.info("Generating unified clinical consultation note (single-pass)...")

        try:
            raw_output = self._model_service.generate(
                prompt=prompt,
                max_new_tokens=600,
                do_sample=False,
                repetition_penalty=1.15,
            )
        except Exception as e:
            logger.error(f"LLM generation failed: {e}")
            raise ClinicalNoteServiceError(f"Note generation failed: {e}") from e

        raw_output = raw_output.strip()

        # Parse output into structured fields
        parsed = parse_clinical_note_markdown(raw_output)

        model_info = self._model_service.model_info
        metadata = NoteMetadata(
            model_name=model_info.get("base_model", "unknown") or "unknown",
            adapter_name=model_info.get("adapter_path", "none") or "none",
        )

        note = ClinicalNote(
            chief_complaint=parsed.get("chief_complaint", "Not documented."),
            history_of_present_illness=parsed.get("history_of_present_illness", "Not documented."),
            past_medical_history=parsed.get("past_medical_history", "Not documented."),
            medications=parsed.get("medications", "Not documented."),
            allergies=parsed.get("allergies", "Not documented."),
            review_of_systems=parsed.get("review_of_systems", "Not documented."),
            examination=parsed.get("examination", "Not documented."),
            assessment=parsed.get("assessment", "Not documented."),
            plan=parsed.get("plan", "Not documented."),
            raw_markdown=raw_output,
            metadata=metadata,
        )

        logger.info("Clinical consultation note generated successfully")
        return note

    def validate_note(self, note: ClinicalNote) -> list[str]:
        """
        Validate a generated clinical note.

        Checks that:
        - Required sections are populated (even if "Not documented.")
        - Metadata is present
        - Note is marked as draft
        """
        warnings = []

        for section_key in SECTION_MAP:
            value = getattr(note, section_key, None)
            if value is None or value == "":
                warnings.append(f"Section '{section_key}' is empty")

        if not note.metadata.is_draft:
            warnings.append("Note is not marked as draft")

        if not note.metadata.generated_at:
            warnings.append("Missing generation timestamp")

        return warnings
