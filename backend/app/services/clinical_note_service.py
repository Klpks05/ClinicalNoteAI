@dataclass
class NoteMetadata:
    """Metadata for a generated clinical note."""

    generated_at: str = ""
    model_name: str = ""
    adapter_name: str = ""
    is_draft: bool = True
    disclaimer: str = (
        "DRAFT — This clinical note was generated by an AI model "
        "and requires clinician verification before clinical use."
    )

    def __post_init__(self):
        if not self.generated_at:
            self.generated_at = datetime.now(timezone.utc).isoformat()


@dataclass
class ClinicalNote:
    """A structured clinical consultation note with all standard sections."""

    chief_complaint: str = "Not documented."
    history_of_present_illness: str = "Not documented."
    past_medical_history: str = "Not documented."
    medications: str = "Not documented."
    allergies: str = "Not documented."
    review_of_systems: str = "Not documented."
    examination: str = "Not documented."
    assessment: str = "Not documented."
    plan: str = "Not documented."
    raw_markdown: str = ""
    metadata: NoteMetadata = field(default_factory=NoteMetadata)

    def to_dict(self) -> dict:
        """Convert to dictionary for API response."""
        return {
            "chief_complaint": self.chief_complaint,
            "history_of_present_illness": self.history_of_present_illness,
            "past_medical_history": self.past_medical_history,
            "medications": self.medications,
            "allergies": self.allergies,
            "review_of_systems": self.review_of_systems,
            "examination": self.examination,
            "assessment": self.assessment,
            "plan": self.plan,
            "raw_markdown": self.raw_markdown or self.to_text(),
            "metadata": {
                "generated_at": self.metadata.generated_at,
                "model_name": self.metadata.model_name,
                "adapter_name": self.metadata.adapter_name,
                "is_draft": self.metadata.is_draft,
                "disclaimer": self.metadata.disclaimer,
            },
        }

    def to_text(self) -> str:
        """Format as plain text paper-style consultation note for export."""
        lines = [
            "=" * 60,
            "CLINICAL CONSULTATION NOTE",
            "(DRAFT — Requires Clinician Review and Verification)",
            "=" * 60,
            "",
            "CHIEF COMPLAINT",
            "-" * 15,
            self.chief_complaint,
            "",
            "HISTORY OF PRESENT ILLNESS",
            "-" * 26,
            self.history_of_present_illness,
            "",
            "RELEVANT MEDICAL HISTORY",
            "-" * 24,
            self.past_medical_history,
            "",
            "CURRENT MEDICATIONS",
            "-" * 19,
            self.medications,
            "",
            "ALLERGIES",
            "-" * 9,
            self.allergies,
            "",
            "REVIEW OF SYSTEMS",
            "-" * 17,
            self.review_of_systems,
            "",
            "PHYSICAL EXAMINATION",
            "-" * 20,
            self.examination,
            "",
            "CLINICAL ASSESSMENT",
            "-" * 19,
            self.assessment,
            "",
            "PLAN AND FOLLOW-UP",
            "-" * 18,
            self.plan,
            "",
            "=" * 60,
            f"Generated: {self.metadata.generated_at}",
            f"Model: {self.metadata.model_name}",
            f"Adapter: {self.metadata.adapter_name}",
            f"Notice: {self.metadata.disclaimer}",
            "=" * 60,
        ]
        return "\n".join(lines)


